"""动作词表 —— 判断用户到底在**要求做什么**。

指代消解和意图识别有一个共同的坑：让"政策/知识类"的词参与判断。
"运费怎么算"和"我要退运费"共享"运费"两个字，但前者是政策咨询、后者是退款，
必须靠**动作词**（怎么算 vs 退）区分，而不是靠话题词。

所以动作词表单独抽出来共用：coreference 用它决定"要不要带订单号"，
intent 用它判断"这句话是在提要求还是在问规则"。放在一个文件里，
是为了让"同一个词在两处的含义必须一致"变成结构上的事实而不是约定。
"""

from __future__ import annotations

#: 需要动到具体订单的动作。这类诉求一旦出现，就必须落到某个订单上，
#: 因此指代消解要优先补订单号（"那它能退吗" → "订单 ORD-1001"）。
#:
#: 两条刻意的取舍：
#:   1. **不收**"退货流程""退款政策"这类词 —— 它们问的是规则，不是动作。
#:      收进来会让"退货流程是什么"被判成需要补订单号，凭空多问用户一句。
#:   2. **不收**"改地址/换成" —— 地址类诉求的作用对象是地址不是订单，
#:      补订单号进句子反而会把"这个能改地址吗"改得更难检索。
ORDER_ACTIONS: tuple[str, ...] = (
    "退款", "退钱", "返钱", "退货", "退掉", "退费",
    "我要退", "能退", "可以退", "想退", "要退", "退它", "退这", "退那",
    "取消", "撤销", "撤单", "能撤", "撤吗", "别发", "不想要",
    "物流", "快递", "发货", "到哪", "运单", "签收", "配送", "几天到",
    "查订单", "查单", "订单状态", "我的单", "买的到",
)


import re

#: 上面那批"动作词"都是带具体动词的，但有一类转折句只有"要/想 + 退/撤"：
#: "我不想买了""订单能撤吗"。这种句式用词表穷举不完，用正则覆盖更省。
ACTION_PATTERNS: tuple[re.Pattern[str], ...] = tuple(
    re.compile(p)
    for p in (
        r"(?:要|想|能|要能|可以|给我|帮我|给我)?\s*(?:退|撤|取消)\s*(?:吗|吧|了|掉)?\s*$",
        r"(?:不想|不要|别)\s*(?:买|要)",
        r"(?:退|撤|取消)(?:款|货|单|掉|了)",
    )
)


def has_order_action(text: str) -> bool:
    """这句话里有没有"必须落到某个订单"的动作。

    用于两处，且口径必须一致：指代消解的语义域判定（没有动作词就别往句子里
    塞订单号）、意图打分的话题折扣（带动作词时政策/商品这类话题词要降权）。
    """
    if any(v in text for v in ORDER_ACTIONS):
        return True
    return any(p.search(text) for p in ACTION_PATTERNS)
