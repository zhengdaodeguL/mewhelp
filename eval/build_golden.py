#: 多轮题里助手那句固定用短句：history 越长，规则层扫实体时越容易被噪声干扰，
#: 保持"助手只说客套话"能让消解结果只由用户那句决定，标注才可复现。
ACK = "好的，我帮您看一下。"


def h(*user_turns: str) -> list[dict[str, str]]:
    """构造 history：用户轮与助手客套话交替。"""
    out: list[dict[str, str]] = []
    for i, u in enumerate(user_turns):
        out.append({"role": "user", "content": u})
        if i < len(user_turns) - 1:
            out.append({"role": "assistant", "content": ACK})
    out.append({"role": "assistant", "content": ACK})
    return out


