"""生成 data/eval/golden.jsonl —— 300 道标注题（5 桶 × 60）。

为什么用脚本生成而不是手写 jsonl：

1. **expected_chunk_ids 必须能对账**。chunk_id 是 `doc_id#序号`，手写极容易
   写成 `退款政策#004`（少一位补零）或 `退款政策#13`（超范围）—— 这种错在
   评估时表现为"某题永远 recall=0"，看起来像检索不行，其实是标注写错。
   脚本直接拿真实切分结果做集合校验，写错就报错退出。

2. **no_answer 桶必须实测**。这个桶的判据是"检索侧最高分 < 0.35"，凭感觉
   造题必然混进一批"沾边词"导致高分命中，拒答桶就变成 0 分桶，失去意义。
   所以生成时先把每条跑一遍检索，分数不达标的直接报出来。

3. **多轮题必须验证消解结果**。question 是半截话，expected_chunk_ids 是
   "消解之后"应该命中的块。如果实际消解出来的句子不是预期的那个实体方向，
   这题的标注就是错的（而不是"模型不行"）。

用法：
    PYTHONPATH=src PYTHONIOENCODING=utf-8 python eval/build_golden.py          # 生成
    PYTHONPATH=src PYTHONIOENCODING=utf-8 python eval/build_golden.py --check   # 只校验不写
"""

